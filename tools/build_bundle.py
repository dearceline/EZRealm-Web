#!/usr/bin/env python3
"""Build a deterministic, self-contained realm.sh with the pinned TOML library."""
import base64
import hashlib
import io
from pathlib import Path
import shlex
import textwrap
import zipfile

import tomlkit

ROOT = Path(__file__).resolve().parent.parent


def build():
    library = Path(tomlkit.__file__).parent
    files = {"entry.py": (ROOT / "entry.py").read_bytes()}
    for path in (ROOT / "ezrealm").rglob("*"):
        if path.is_file() and "__pycache__" not in path.parts:
            files[path.relative_to(ROOT).as_posix()] = path.read_bytes()
    for path in library.rglob("*"):
        if path.is_file() and "__pycache__" not in path.parts:
            files["tomlkit/" + path.relative_to(library).as_posix()] = path.read_bytes()
    # tomlkit is MIT licensed; keep its exact attribution in the payload.
    import importlib.metadata
    distribution = importlib.metadata.distribution("tomlkit")
    if distribution.version != "0.13.3":
        raise RuntimeError("Build requires tomlkit==0.13.3")
    files["TOMLKIT-LICENSE"] = distribution.read_text("LICENSE").encode()
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3  # Stable ZIP header on Windows and Linux.
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    data = buffer.getvalue()
    digest = hashlib.sha256(data).hexdigest()
    encoded = "\n".join(textwrap.wrap(base64.b64encode(data).decode(), 100))
    bootstrap = '''import base64, hashlib, io, os, pathlib, shutil, sys, tempfile, zipfile
if sys.version_info < (3, 11):
    raise SystemExit("需要 Python 3.11+；推荐 Debian 12 / Ubuntu 24.04")
if sys.platform != "linux":
    raise SystemExit("安装仅支持 Linux")
payload = base64.b64decode("""
PAYLOAD
""")
expected = "DIGEST"
if hashlib.sha256(payload).hexdigest() != expected:
    raise SystemExit("内置程序校验失败")
root = pathlib.Path("/opt/ezrealm-web/releases")
root.mkdir(parents=True, exist_ok=True, mode=0o755)
destination = root / expected[:20]
if not destination.exists():
    temporary = pathlib.Path(tempfile.mkdtemp(prefix=".install-", dir=root))
    try:
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            for info in archive.infolist():
                member = pathlib.PurePosixPath(info.filename)
                if member.is_absolute() or ".." in member.parts:
                    raise SystemExit("非法内置文件路径")
            archive.extractall(temporary)
        for item in temporary.rglob("*"):
            os.chmod(item, 0o755 if item.is_dir() else 0o644)
        os.chmod(temporary, 0o755)
        try:
            temporary.rename(destination)
        except FileExistsError:
            pass
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
os.execv(sys.executable, [sys.executable, str(destination / "entry.py"), "cli", *sys.argv[1:]])
'''.replace("PAYLOAD", encoded).replace("DIGEST", digest)
    script = '''#!/usr/bin/env bash
# EZRealm-Web 1.0.0. Generated by tools/build_bundle.py; do not hand edit payload.
set -euo pipefail
if [ "${EUID}" -ne 0 ]; then
  echo "请使用 root 运行：sudo bash realm.sh" >&2
  exit 1
fi
if ! command -v python3 >/dev/null 2>&1; then
  echo "需要 Python 3.11+。Debian 12 / Ubuntu 24.04：apt-get update && apt-get install -y python3 ca-certificates" >&2
  exit 1
fi
'''
    # -c preserves the original standard input for menu 12 and its EOF handling.
    script += 'exec python3 -c ' + shlex.quote(bootstrap) + ' "$@"\n'
    (ROOT / "realm.sh").write_text(script, encoding="utf-8", newline="\n")
    print(f"realm.sh built: {len(data)} payload bytes, sha256={digest}")


if __name__ == "__main__":
    build()
